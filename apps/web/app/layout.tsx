import "@workspace/ui/globals.css";

import type { Metadata } from "next";
import { Open_Sans } from "next/font/google";
import { ClerkProvider } from "@clerk/nextjs";

import { ThemeProvider } from "@/features/components/providers/theme-provider";
import { ModalProvider } from "@/features/components/providers/modal-provider";
import { cn } from "@/lib/utils";
import { SocketProvider } from "@/features/components/providers/socket-provider";
import { QueryProvider } from "@/features/components/providers/query-provider";

const font = Open_Sans({ subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Team Chat Application",
  description: "Generated by create next app",
};

// Root layout for the whole app. Wraps every page in the providers it depends on:
// Clerk (authentication), the theme (dark/light mode), the socket connection,
// TanStack Query (data fetching), and the shared modals.
export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <ClerkProvider>
      <html lang="en" className="h-full" suppressHydrationWarning>
        <body className={cn(font.className, "h-dvh bg-white dark:bg-[#313338]")}>
          {/* Dark mode is the default; the choice is saved under "discord-theme". */}
          <ThemeProvider
            attribute="class"
            defaultTheme="dark"
            enableSystem
            storageKey="discord-theme"
          >
             {/* Opens the real-time socket connection once the user is signed in. */}
             <SocketProvider>
                      <QueryProvider>
                         {/* Renders every modal once, so any component can open one. */}
                         <ModalProvider />
                          {children}
                       </QueryProvider>
             </SocketProvider>
          </ThemeProvider>
        </body>
      </html>
    </ClerkProvider>
  );
}